def attachTwins(L):
    """التوأم مسألة جديدة على الطفل في ما يعيشه (الدرس 132): لا يعيد ما قبل التمرين، ولا مسألة بندٍ في مساره ولا في العلاج بعده،
    ولا توأماً آخر في مساره؛ وتوأم العلاج لا يعيد شيئاً من المسارات. ومسائل التقييم في الوحدة كلها ممنوعة إلا ما يُحسب بين التقييمات وحدها
    (عدّ فراغات الإطار ولمحته، كما في d240). يُحلّ بالتراجع، ويحسمه build/d240.mjs."""
    T = TWINS[L['id']]; B0 = before(L)
    P = twinPaths(L); items = []; seen = set()
    for k in ('A', 'B', 'C'):
        for it in P[k]:
            if id(it) not in seen: seen.add(id(it)); items.append(it)
    mem = {id(it): {k for k in P if any(x is it for x in P[k])} for it in items}
    F = {k: {tkey(x) for x in P[k]} for k in P}
    bad0 = B0 | ASSESS
    def forbid(it):
        m = mem[id(it)]; s = set(bad0) | {tkey(it)} | F['C']
        for k in ('A', 'B'):
            if k in m or 'C' in m: s |= F[k]
        return s
    def cands(it):
        c = [x for x in T['pool'].get(skill(it), [])] + [x for x in items if x is not it and skill(x) == skill(it)]
        out, fs = [], set()
        for x in c:
            f = tkey(x)
            if f in forbid(it) or f in fs or norm(x) in ASSESS_N: continue
            fs.add(f); out.append(x)
        return out
    C = {id(it): cands(it) for it in items}
    for it in items: assert C[id(it)], ('لا توأم', L['id'], it.get('q'), skill(it), sorted(mem[id(it)]))
    def clash(a, fa, b, fb): return fa == fb and bool(mem[id(a)] & mem[id(b)])
    order = sorted(items, key=lambda it: len(C[id(it)])); pick = {}
    def solve(i):
        if i == len(order): return True
        it = order[i]
        for x in C[id(it)]:
            f = tkey(x)
            if any(clash(it, f, o, tkey(pick[id(o)])) for o in order[:i]): continue
            pick[id(it)] = x
            if solve(i + 1): return True
            del pick[id(it)]
        return False
    if not solve(0):
        for it in items: print('  ', it.get('q'), skill(it), sorted(mem[id(it)]), [tkey(x) for x in C[id(it)]])
        raise AssertionError(('لا توزيع للتوائم', L['id']))
    for it in items: it['twin'] = json.loads(json.dumps(pick[id(it)])); it['twin'].pop('twin', None)
    used = lineIds([it['twin'] for it in items], set())
    for k, v in T['lines'].items():
        if k in used: assert k not in L['lines'], (L['id'], k); L['lines'][k] = v
