# ---------- 1) D190: جا وجتا وظا، وص = م س + ب ----------
TRIG = {'sin': 'جا', 'cos': 'جتا', 'tan': 'ظا'}
def trig(t): return re.sub(r'(?<![A-Za-z])(sin|cos|tan)(?![A-Za-z])', lambda m: TRIG[m.group(1)], t)
LIN = {'y': 'ص', 'x': 'س', 'm': 'م', 'b': 'ب'}
def lin(t):
    t = re.sub(r'(?<![A-Za-z])mx(?![A-Za-z])', 'م س', t)            # y = mx + b
    return re.sub(r'(?<![A-Za-z])([yxmb])(?![A-Za-z])', lambda m: LIN[m.group(1)], t)
def conv_fields(x, f):
    d = {}
    for k in ('q', 'hint', 'correct'):
        if isinstance(x.get(k), str) and f(x[k]) != x[k]: d[k] = f(x[k])
    for k in ('wrongs', 'steps'):
        if x.get(k) and [f(w) for w in x[k]] != x[k]: d[k] = [f(w) for w in x[k]]
    return d
